package main

import (
	"bufio"
	"context"
	"encoding/json"
	"fmt"
	"os"
	"strings"

	sigma "github.com/bradleyjkemp/sigma-go"
	"gopkg.in/yaml.v3"

	"github.com/samma-io/detection-engine/internal/decode"
	"github.com/samma-io/detection-engine/internal/rules"
)

// sampleSet is real records from one lane, read out of the filtered bucket.
//
// It exists because the fixture problem generalises badly. TrailAlerts supplies
// real CloudTrail records keyed by SigmaHQ rule id, which solved the aws lane
// and nothing else -- there is no equivalent corpus for github, gcp, workspace,
// slack or onepassword. But we have something better for those: the records
// themselves.
//
// Deriving a sidecar from real traffic also answers a question a hand-written
// fixture cannot. A rule that matches nothing in a day of our own logs is not
// necessarily wrong, but it is unproven here, and saying so is more useful than
// asserting coverage.
type sampleSet struct {
	Lane    string
	Records []map[string]any
}

func loadSamples(path, lane string) (*sampleSet, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer func() { _ = f.Close() }()

	s := &sampleSet{Lane: lane}
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 0, 1<<20), 8<<20)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if line == "" {
			continue
		}
		var rec map[string]any
		if err := json.Unmarshal([]byte(line), &rec); err != nil {
			continue // one bad line is not worth failing an import over
		}
		// Vector stamps source on every record; a sample pulled from the raw
		// side may not have it, and every rule and guard expects it.
		if _, ok := rec["source"]; !ok {
			rec["source"] = lane
		}
		s.Records = append(s.Records, rec)
	}
	return s, sc.Err()
}

// evidence is what a candidate rule did against real traffic.
type evidence struct {
	Matched     []map[string]any
	NotMatched  []map[string]any
	Total       int
	LostToScrub int // matched the raw record but not the scrubbed one
}

// test runs one rule against the sample, using the same match path the engine
// uses so that a positive here means a positive in production.
func (s *sampleSet) test(name string, body []byte, cfg []sigma.Config) (*evidence, error) {
	set, err := rules.Compile([]rules.File{{Name: name, Data: body}}, cfg)
	if err != nil {
		return nil, err
	}
	ev := &evidence{Total: len(s.Records)}
	for _, rec := range s.Records {
		m, _, err := set.Match(context.Background(), decode.MatchView(rec))
		if err != nil {
			continue
		}

		// Nothing from the filtered bucket is written as-is: it is tagged
		// contains_PII_data and a sidecar lives in git forever.
		clean := scrubRecord(rec)

		if len(m) > 0 {
			if len(ev.Matched) >= maxPositive {
				continue
			}
			// Scrubbing must not change the verdict. If the rule stops firing
			// once identifiers are removed, then it was matching on one of
			// them, and this record cannot become a safe test case -- keeping
			// it would either leak the identifier or assert a match that no
			// longer happens.
			m2, _, err := set.Match(context.Background(), decode.MatchView(clean))
			if err != nil || len(m2) == 0 {
				ev.LostToScrub++
				continue
			}
			ev.Matched = append(ev.Matched, clean)
			continue
		}

		if len(ev.NotMatched) < maxNegative {
			// A negative must still not match after scrubbing, or it proves
			// nothing about the rule.
			m2, _, err := set.Match(context.Background(), decode.MatchView(clean))
			if err == nil && len(m2) == 0 {
				ev.NotMatched = append(ev.NotMatched, clean)
			}
		}
	}
	return ev, nil
}

const (
	maxPositive = 2
	maxNegative = 3
)

// sidecarFromEvidence writes cases proving the rule fires on records this
// estate actually produced.
func sidecarFromEvidence(ev *evidence, lane, upstream string) ([]byte, int, error) {
	if len(ev.Matched) == 0 {
		return nil, 0, fmt.Errorf("no match in %d sample records", ev.Total)
	}

	type testCase struct {
		Name     string         `yaml:"name"`
		Expected bool           `yaml:"expected"`
		Event    map[string]any `yaml:"event"`
	}
	var cases []testCase
	for i, e := range ev.Matched {
		cases = append(cases, testCase{
			Name:     fmt.Sprintf("real %s record fires (%d)", lane, i+1),
			Expected: true,
			Event:    e,
		})
	}
	for i, e := range ev.NotMatched {
		cases = append(cases, testCase{
			Name:     fmt.Sprintf("unrelated real %s record does not fire (%d)", lane, i+1),
			Expected: false,
			Event:    e,
		})
	}

	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by hack/sigmaimport from REAL records in the filtered\n")
	fmt.Fprintf(&b, "# bucket, not from the rule. %d of %d sampled %s records matched.\n",
		len(ev.Matched), ev.Total, lane)
	fmt.Fprintf(&b, "#\n# Identifiers are SCRUBBED -- emails, public IPs, account ids, principal\n")
	fmt.Fprintf(&b, "# ids and tokens are replaced with documentation-range equivalents of the\n")
	fmt.Fprintf(&b, "# same shape. The filtered bucket is contains_PII_data; a sidecar is not.\n")
	fmt.Fprintf(&b, "# Every case here was re-matched AFTER scrubbing, so the redaction cannot\n")
	fmt.Fprintf(&b, "# have quietly invalidated the test.\n")
	fmt.Fprintf(&b, "#\n# Upstream: %s\n", upstream)
	fmt.Fprintf(&b, "#\n# These are production shapes. Do not trim fields to make them tidy --\n")
	fmt.Fprintf(&b, "# the whole value is that the rule is proven against what the source\n")
	fmt.Fprintf(&b, "# actually emits, including the fields nobody remembered.\n")
	out, err := yaml.Marshal(cases)
	if err != nil {
		return nil, 0, err
	}
	b.Write(out)
	return []byte(b.String()), len(cases), nil
}
